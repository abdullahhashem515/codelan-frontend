// Security headers for the production build — one source for both the CSP
// <meta> injected into index.html and the .htaccess written into dist/.
//
// Hosting is Hostinger (LiteSpeed, reads .htaccess) behind Cloudflare. Headers
// set in .htaccess reach the browser; the <meta> CSP is a second layer that
// still applies if a proxy ever strips them, and it works when the files are
// served from somewhere that ignores .htaccess.

const API_ORIGIN = 'https://back-end.codelanco.com';

// What the site actually loads, and nothing else:
//  • scripts   — only its own bundle. No inline script, no eval. This is the
//                line that makes an injected <script> or javascript: payload
//                inert even if one got past everything else.
//  • styles    — own CSS, plus inline: React and the toast library set styles
//                at runtime, and style injection is not a script-execution
//                vector the way script injection is.
//  • images    — own files and any https host: project screenshots and
//                uploads can live anywhere.
//  • connect   — the API only. Script cannot send data anywhere else.
//  • fonts     — self-hosted.
//  • frames    — the two video players only (motion-graphics work), and only
//                after a visitor presses play (components/VideoEmbed).
const CSP_DIRECTIVES = {
  'default-src': ["'self'"],
  'script-src': ["'self'"],
  'style-src': ["'self'", "'unsafe-inline'"],
  'img-src': ["'self'", 'data:', 'blob:', 'https:'],
  'font-src': ["'self'"],
  'connect-src': ["'self'", API_ORIGIN],
  'media-src': ["'self'", 'https:'],
  'object-src': ["'none'"],
  'frame-src': ['https://www.youtube-nocookie.com', 'https://player.vimeo.com'],
  'worker-src': ["'self'", 'blob:'],
  'manifest-src': ["'self'"],
  'base-uri': ["'self'"],
  'form-action': ["'self'"],
};

const serialize = (d) => Object.entries(d).map(([k, v]) => `${k} ${v.join(' ')}`).join('; ');

// <meta> cannot carry frame-ancestors (browsers ignore it there), so the
// header version adds it: no site may put this one in a frame (clickjacking).
export const CSP_META = `${serialize(CSP_DIRECTIVES)}; upgrade-insecure-requests`;
export const CSP_HEADER = `${serialize({ ...CSP_DIRECTIVES, 'frame-ancestors': ["'none'"] })}; upgrade-insecure-requests`;

export const HTACCESS = `# Generated by the build (vite.config.js + security.config.js) — edit there, not here.
# Replaces the .htaccess on the server: it includes the single-page-app fallback
# the live site already relies on, so deep links like /admin/login keep working.

Options -Indexes

# ── Single-page app: every unknown path serves index.html ──────────────────────
<IfModule mod_rewrite.c>
  RewriteEngine On
  RewriteBase /
  RewriteRule ^index\\.html$ - [L]
  # Link-preview bots (WhatsApp, Facebook, X, Telegram, LinkedIn, Slack,
  # Discord…) go to the backend's share pages, which are always current —
  # including articles and projects added after the last build. Search engines
  # are deliberately not in the list: they stay on this domain and get the
  # pre-rendered page below.
  RewriteCond %{HTTP_USER_AGENT} (facebookexternalhit|facebookcatalog|Facebot|Twitterbot|WhatsApp|TelegramBot|LinkedInBot|Slackbot|Discordbot|SkypeUriPreview|Pinterestbot|redditbot|vkShare|Embedly) [NC]
  RewriteRule ^blog/([^/]+)/?$ https://back-end.codelanco.com/share/blog/$1 [R=302,L,NE]
  RewriteCond %{HTTP_USER_AGENT} (facebookexternalhit|facebookcatalog|Facebot|Twitterbot|WhatsApp|TelegramBot|LinkedInBot|Slackbot|Discordbot|SkypeUriPreview|Pinterestbot|redditbot|vkShare|Embedly) [NC]
  RewriteRule ^projects/([0-9]+)/?$ https://back-end.codelanco.com/share/projects/$1 [R=302,L]
  # Pre-rendered pages (scripts/seo-build.mjs): /blog/<slug> → blog/<slug>.html,
  # so link previews and crawlers get each page's own title, text and image.
  RewriteCond %{REQUEST_FILENAME}.html -f
  RewriteRule ^(.+?)/?$ $1.html [L]
  RewriteCond %{REQUEST_FILENAME} !-f
  RewriteCond %{REQUEST_FILENAME} !-d
  RewriteRule . /index.html [L]
</IfModule>

# ── Security headers ────────────────────────────────────────────────────────────
<IfModule mod_headers.c>
  Header always set Content-Security-Policy "${CSP_HEADER}"
  # HTTPS only, for a year. Deliberately without includeSubDomains/preload:
  # every subdomain would then be forced onto HTTPS too, and one without a
  # certificate (a mail or panel host) would become unreachable.
  Header always set Strict-Transport-Security "max-age=31536000"
  Header always set X-Content-Type-Options "nosniff"
  Header always set X-Frame-Options "DENY"
  Header always set Referrer-Policy "strict-origin-when-cross-origin"
  Header always set Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()"
  Header always set Cross-Origin-Opener-Policy "same-origin"
  Header always unset X-Powered-By

  # index.html must always be revalidated, so a deploy (and any security fix
  # in it) reaches visitors immediately instead of after a cache expires.
  <FilesMatch "^index\\.html$">
    Header set Cache-Control "no-cache, must-revalidate"
  </FilesMatch>
</IfModule>

# ── Never serve dotfiles, source maps or backups ───────────────────────────────
<FilesMatch "(^\\.|\\.map$|\\.(bak|old|orig|swp|log|sql|env)$)">
  Require all denied
</FilesMatch>
`;

// dist/assets/ holds only content-hashed files: a changed file gets a new name,
// so these can be cached for a year without ever serving a stale one.
export const HTACCESS_ASSETS = `# Generated by the build — content-hashed files, safe to cache for a year.
<IfModule mod_headers.c>
  Header set Cache-Control "public, max-age=31536000, immutable"
</IfModule>
`;
